let historiaActual = 0;
let capituloActual = 0;

function mostrarCatalogo() {
  const catalogo = document.getElementById("historiaCatalogo");
  catalogo.innerHTML = "";
  historias.forEach((historia, index) => {
    const div = document.createElement("div");
    div.className = "historia-card";
    div.innerHTML = `
      <img src="${historia.imagen}" alt="${historia.titulo}">
      <p>${historia.titulo}</p>
    `;
    div.addEventListener("click", () => {
      historiaActual = index;
      capituloActual = 0;
      document.getElementById("lector").style.display = "block";
      document.getElementById("historiaCatalogo").style.display = "none";
      mostrarCapitulo();
    });
    catalogo.appendChild(div);
  });
}

function mostrarCapitulo() {
  const historia = historias[historiaActual];
  document.getElementById("historiaTitulo").textContent = historia.titulo;
  document.getElementById("historiaContenido").innerHTML = 
    historia.capitulos[capituloActual].replace(/\n/g, "<br>");

  // Botones
  document.getElementById("anteriorCap").disabled = capituloActual === 0;
  document.getElementById("siguienteCap").disabled = 
    capituloActual === historia.capitulos.length - 1;
}

document.getElementById("anteriorCap").addEventListener("click", () => {
  if (capituloActual > 0) {
    capituloActual--;
    mostrarCapitulo();
  }
});

document.getElementById("siguienteCap").addEventListener("click", () => {
  const historia = historias[historiaActual];
  if (capituloActual < historia.capitulos.length - 1) {
    capituloActual++;
    mostrarCapitulo();
  }
});

document.addEventListener("DOMContentLoaded", () => {
  mostrarCatalogo();
});
function volverAlCatalogo() {
  document.getElementById("lector").style.display = "none";
  document.getElementById("historiaCatalogo").style.display = "flex";
}

